CREATE TABLE CLASSROOM (
  ClassroomCode INTEGER PRIMARY KEY,
  ClassroomName VARCHAR NOT NULL,
  Capacity INTEGER NOT NULL
);
CREATE TABLE COURSE (
  CourseCode INTEGER PRIMARY KEY,
  CourseName VARCHAR NOT NULL,
  ECTSCredit INTEGER NOT NULL,
  EnrolledCount INTEGER NOT NULL
);
CREATE TABLE LECTURE (
  ClassroomCode INTEGER NOT NULL REFERENCES CLASSROOM(ClassroomCode),
  Date DATE NOT NULL,
  StartTime TIME NOT NULL,
  CourseCode INTEGER NOT NULL REFERENCES COURSE(CourseCode),
  PRIMARY KEY (ClassroomCode, Date, StartTime)
);
