CREATE TABLE AUTHOR (
  AuthorCode INTEGER PRIMARY KEY,
  AuthorName VARCHAR NOT NULL,
  DateOfBirth DATE NOT NULL,
  City VARCHAR NOT NULL
);
CREATE TABLE BOOK_PUBLISHED (
  ISBN VARCHAR PRIMARY KEY,
  Title VARCHAR NOT NULL,
  AuthorCode INTEGER NOT NULL REFERENCES AUTHOR(AuthorCode),
  Genre VARCHAR NOT NULL
);
CREATE TABLE SALE (
  SaleCode INTEGER PRIMARY KEY,
  ISBN VARCHAR NOT NULL REFERENCES BOOK_PUBLISHED(ISBN),
  Date DATE NOT NULL,
  Time TIME NOT NULL,
  Price DECIMAL(8,2) NOT NULL
);
