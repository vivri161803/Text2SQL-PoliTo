CREATE TABLE STUDENT (
  StudentCode INTEGER PRIMARY KEY,
  StudentName VARCHAR NOT NULL,
  SchoolType VARCHAR NOT NULL,
  SchoolYear INTEGER NOT NULL,
  Section VARCHAR NOT NULL
);
CREATE TABLE TEACHER (
  TeacherCode INTEGER PRIMARY KEY,
  TeacherName VARCHAR NOT NULL,
  Profession VARCHAR NOT NULL
);
CREATE TABLE CONSULTATION (
  TeacherCode INTEGER NOT NULL REFERENCES TEACHER(TeacherCode),
  Date DATE NOT NULL,
  StartTime TIME NOT NULL,
  Duration INTEGER NOT NULL,
  Topic VARCHAR NOT NULL,
  ConsultationCost DECIMAL(8,2) NOT NULL,
  StudentCode INTEGER NOT NULL REFERENCES STUDENT(StudentCode),
  PRIMARY KEY (TeacherCode, Date, StartTime)
);
